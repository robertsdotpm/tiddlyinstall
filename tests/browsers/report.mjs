// The browser results grid: machine x browser, the latest result of each
// pair from tests/browsers/usage.jsonl, with what's installed from
// inventory.json.
//
//   node tests/browsers/report.mjs            # print it (Markdown)
//   node tests/browsers/report.mjs --write    # replace the section in docs/test-results.md
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const DOC = path.join(HERE, '..', '..', 'docs', 'test-results.md');
const START = '<!-- browsers:start (tests/browsers/report.mjs) -->';
const END = '<!-- browsers:end -->';

const ORDER = ['xp', 'vista', '7', '8.1', '10', '11', '2022', 'centos6', 'centos7', 'ubuntu1404', 'ubuntu1604', 'ubuntu1804',
  'rocky8', 'ubuntu2004', 'ubuntu2204', 'debian12', 'alpine', 'mac'];
const LABEL = { xp: 'Windows XP', vista: 'Vista', 7: 'Windows 7', 8.1: 'Windows 8.1', 10: 'Windows 10', 11: 'Windows 11', 2022: 'Server 2022',
  centos6: 'CentOS 6', centos7: 'CentOS 7', ubuntu1404: 'Ubuntu 14.04', ubuntu1604: 'Ubuntu 16.04', ubuntu1804: 'Ubuntu 18.04',
  rocky8: 'Rocky 8', ubuntu2004: 'Ubuntu 20.04', ubuntu2204: 'Ubuntu 22.04', debian12: 'Debian 12', alpine: 'Alpine 3.24', mac: 'macOS 26' };
const BROWSERS = ['chrome', 'chromium', 'edge', 'supermium', 'firefox', 'safari'];
const BLABEL = { chrome: 'Chrome', chromium: 'Chromium', edge: 'Edge', supermium: 'Supermium', firefox: 'Firefox', safari: 'Safari' };

const inv = JSON.parse(fs.readFileSync(path.join(HERE, 'inventory.json'), 'utf8'));
const usage = fs.existsSync(path.join(HERE, 'usage.jsonl'))
  ? fs.readFileSync(path.join(HERE, 'usage.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];

const latest = new Map(), runs = new Map();
for (const u of usage) {
  const k = u.machine + '/' + u.browser;
  runs.set(k, (runs.get(k) || 0) + 1);
  // An infrastructure error doesn't replace a real result.
  if (!/^error/.test(u.result) || !latest.has(k) || /^error/.test(latest.get(k).result)) latest.set(k, u);
}

const major = (v) => String(v || '').split('.')[0];
const cols = BROWSERS.filter((b) => Object.values(inv.machines).some((m) => (m.browsers || []).some((x) => x.id === b)));
const lines = [];
lines.push(`| Machine | ${cols.map((c) => BLABEL[c]).join(' | ')} |`, `| --- | ${cols.map(() => '---').join(' | ')} |`);
const notes = [];
let counts = { pass: 0, fail: 0, unsupported: 0, error: 0, untested: 0, none: 0 };
for (const name of ORDER.filter((n) => inv.machines[n])) {
  const m = inv.machines[name];
  const cells = cols.map((b) => {
    const e = (m.browsers || []).find((x) => x.id === b);
    if (!e) return '';
    if (!e.binary) { counts.none++; notes.push(`${LABEL[name]} ${BLABEL[b]}: can't run here: ${e.notes || ''}`); return 'can\'t run'; }
    const u = latest.get(name + '/' + b);
    const v = major(u && u.version || e.version);
    if (!u) { counts.untested++; return (e.driver ? 'untested ' : 'no driver ') + v; }
    const kind = u.result.split(':')[0];
    counts[kind] = (counts[kind] || 0) + 1;
    if (kind !== 'pass') notes.push(`${LABEL[name]} ${BLABEL[b]} ${u.version}: ${u.result}`);
    return { pass: `✓ ${v}`, fail: `✗ ${v}`, unsupported: `too old ${v}`, error: `error ${v}` }[kind] || kind;
  });
  lines.push(`| ${LABEL[name]} | ${cells.join(' | ')} |`);
}
const total = usage.length;
const out = [START, '',
  `Generated by \`tests/browsers/report.mjs\` from \`tests/browsers/usage.jsonl\` (${total} runs; the latest real result for each pair, `,
  'with the major version it ran). ✓ every check passed · ✗ a check failed · too old: the page\'s startup check found missing features ',
  '(it says so on screen) · error: the run couldn\'t be done (driver, SSH) · can\'t run: the browser doesn\'t start on that OS.', '',
  ...lines, '',
  `**${Object.entries(counts).filter(([, n]) => n).map(([k, n]) => `${n} ${k}`).join(', ')}.**`, '',
  ...(notes.length ? ['Not passing:', '', ...notes.map((n) => '- ' + n.replace(/\|/g, '\\|')), ''] : []),
  END].join('\n');

if (process.argv.includes('--write')) {
  let doc = fs.readFileSync(DOC, 'utf8');
  if (doc.includes(START)) doc = doc.slice(0, doc.indexOf(START)) + out + doc.slice(doc.indexOf(END) + END.length);
  else doc = doc.replace(/\s*$/, '\n\n## Browsers (the one-file page)\n\n' + out + '\n');
  fs.writeFileSync(DOC, doc);
  console.log('wrote ' + DOC);
} else console.log(out);
